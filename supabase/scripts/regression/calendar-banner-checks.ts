import { strict as assert } from "node:assert";
import { calendarBanner } from "@/lib/deadlines/calendar-banner";
import { getApplicationNotices } from "@/lib/deadlines";
import type { LiveVerifiedDeadline } from "@/lib/deadlines/live-schema";
const now = new Date("2026-11-26T08:00:00Z");
const selection = { program: "GKS-U", track: "embassy", cycle: "2027" };
assert.equal(calendarBanner(selection, [], now).title, "No upcoming verified deadline");
assert.equal(calendarBanner({ ...selection, track: "university" }, [], now).title, "No upcoming verified deadline");
assert.equal(calendarBanner({ program: "GKS-G", track: "university", cycle: "2027" }, [], now).title, "No upcoming verified deadline");
assert.equal(calendarBanner({ ...selection, cycle: null }, [], now).title, "Choose your application cycle");
assert.equal(calendarBanner({ ...selection, track: "" }, [], now).source, null);
const live: LiveVerifiedDeadline = { id: "fixture", program: "GKS-U", track: "embassy", cycle: "2027", deadlineType: "document_deadline", label: "Synthetic regression deadline", deadline: "2026-12-02", timezone: null, scopeType: "global", country: null, university: null, sourceUrl: "https://example.org/fixture", sourceNoticeId: null, confidence: null, verificationSource: "admin" };
assert.equal(calendarBanner(selection, [live], now).source, live.sourceUrl);
assert.equal(calendarBanner({ ...selection, track: "university" }, [live], now).source, null);
assert.equal(calendarBanner({ ...selection, cycle: "2028" }, [live], now).source, null);
assert.equal(calendarBanner({ ...selection, track: "" }, [live], now).source, null);
assert.equal(calendarBanner(selection, [{ ...live, scopeType: "country", country: "India" }], now).source, null);
assert.equal(calendarBanner(selection, [{ ...live, deadlineType: "result" }], now).source, null);
assert.equal(calendarBanner(selection, [{ ...live, deadline: "2026-09-30" }], now).source, null);
const expired = getApplicationNotices({ ...selection, program: "GKS-U", track: "embassy", live: [live], now: new Date("2026-12-03T00:00:00Z") });
assert.equal(expired.upcoming.length, 0);
assert.equal(expired.historical.find(d => d.id === "live:fixture")?.daysUntil, -1);
const today = getApplicationNotices({ ...selection, program: "GKS-U", track: "embassy", live: [live], now: new Date("2026-12-02T00:00:00Z") });
assert.equal(today.upcoming.find(d => d.id === "live:fixture")?.daysUntil, 0);
console.log("Verified home calendar regression checks passed.");
