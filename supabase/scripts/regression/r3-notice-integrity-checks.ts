import assert from "node:assert/strict";
import { classifyNotice, classifyProgram, noticeIntake } from "@/lib/notices/classify";
import { parseNoticeList } from "@/lib/notices/study-in-korea";
import { filterPublishedNotices, noticeAppliesTo, type PublishedGksNotice } from "@/lib/notices/published-schema";
import { getApplicationNotices } from "@/lib/deadlines";

assert.equal(classifyProgram("2027 Global Korea Scholarship for Undergraduate Degrees"), "GKS-U");
assert.equal(classifyProgram("2027 GKS Undergraduate Program - University Track"), "GKS-U");
assert.equal(classifyProgram("2027년 정부초청 외국인 학부 장학생 모집 요강"), "GKS-U");
assert.equal(classifyProgram("2027 GKS Korea-Japan Graduate Degree Program"), "unknown");
assert.equal(classifyProgram("2026 Seoul Global Job Fair for graduate program students"), "unknown");
assert.equal(classifyNotice("General education fair", "2027 GKS-U and other opportunities").program, "unknown");
assert.equal(noticeIntake("2027년 정부초청 외국인 학부 장학생 모집 요강"), "2027");
assert.equal(noticeIntake("2027 GKS-U compared with 2026"), null);
assert.equal(noticeIntake("GKS-U announcement"), null);
assert.equal(noticeIntake("2027 GKS Korea-Japan Graduate Degree Program"), null);
const fixture = '<a class="board-text-item" onclick="scholarshipsRead(\'4522\', \'BBSMSTR_000000000461\')"><p class="title">2027 GKS-U Application Guidelines</p><span class="date">2026-09-09</span></a>';
const parsed = parseNoticeList(fixture, "scholarship");
assert.equal(parsed.length, 1);
assert.equal(new URL(parsed[0].sourceUrl).pathname, "/ko/notice/scholarshipsRead.do");
assert.equal(new URL(parsed[0].sourceUrl).searchParams.get("nttId"), "4522");
assert.equal(parseNoticeList("<html>no notice rows</html>", "scholarship").length, 0);
const notice: PublishedGksNotice = { id:"fixture",title:"2027 GKS-U guideline",sourceUrl:"https://www.studyinkorea.go.kr/ko/notice/scholarshipsRead.do?bbsId=BBSMSTR_000000000461&nttId=4522",sourceNoticeId:"4522",publishedAt:"2026-09-09",language:"en",program:"GKS-U",cycle:"2027",track:null,noticeType:"guideline",publisher:"NIIED",reviewed:true };
assert.equal(noticeAppliesTo(notice,"GKS-U","embassy","2027"), true);
assert.equal(noticeAppliesTo(notice,"GKS-U","embassy","2026"), false);
assert.equal(noticeAppliesTo(notice,"GKS-U","embassy",""), false);
assert.equal(noticeAppliesTo({...notice,cycle:null},"GKS-U","embassy","2027"), false);
assert.equal(noticeAppliesTo({...notice,track:"university"},"GKS-U","embassy","2027"), false);
assert.deepEqual(filterPublishedNotices([notice,{...notice,id:"old",cycle:"2026"}],{cycle:"2027"}).map(n=>n.id),["fixture"]);
const now = new Date("2026-11-26T09:00:00Z");
const undergrad = getApplicationNotices({program:"GKS-U",track:"university",cycle:"2027",now});
assert.ok(undergrad.notices.some(n=>n.source.url.includes("nttId=4527")));
assert.ok(undergrad.notices.some(n=>n.source.url.includes("nttId=4522")));
assert.equal(undergrad.upcoming.length,0);
const embassy = getApplicationNotices({program:"GKS-U",track:"embassy",cycle:"2027",now});
assert.ok(!embassy.notices.some(n=>n.source.url.includes("nttId=4527")));
const grad = getApplicationNotices({program:"GKS-G",track:"embassy",cycle:"2027",now});
assert.equal(grad.notices.length,0);
assert.equal(grad.upcoming.length,0);
console.log("R3 scholarship board, intake and curated notice checks passed.");
