import assert from "node:assert/strict";
import { resolveReadinessIntake, readinessYearOptions, canSetProfileIntake } from "@/lib/readiness/intake";
import { storageKeyFor } from "@/lib/readiness/application";
import { editionMatches } from "@/lib/gks/guideline-editions";
import { savedApplicationFromReadiness } from "@/lib/applications/readiness-adapter";
const now = new Date("2026-11-26T12:00:00Z");
assert.equal(resolveReadinessIntake(undefined, "GKS-U", "GKS-U", 2027), "2027");
assert.equal(resolveReadinessIntake("2028", "GKS-U", "GKS-U", 2027), "2028");
assert.equal(resolveReadinessIntake("2027", "GKS-G", "GKS-U", 2028), "2027");
assert.equal(resolveReadinessIntake(undefined, "GKS-G", "GKS-U", 2027), null);
assert.equal(resolveReadinessIntake("bad", "GKS-U", "GKS-U", 2027), null);
assert.equal(resolveReadinessIntake(["2027","2028"], "GKS-U", "GKS-U", 2027), null);
assert.equal(resolveReadinessIntake("2027", "", "GKS-U", 2027), null);
assert.deepEqual(readinessYearOptions("GKS-U", "GKS-U", 2026, "2026", now), ["2026","2027","2028","2029"]);
assert.deepEqual(readinessYearOptions("GKS-G", "GKS-U", 2026, null, now), ["2027","2028","2029"]);
assert.equal(canSetProfileIntake("GKS-U", "gks_u", 2028, 2027, now), true);
assert.equal(canSetProfileIntake("GKS-G", "gks_u", 2028, 2027, now), false);
assert.equal(canSetProfileIntake("GKS-U", "gks_u", 2026, 2027, now), false);
assert.equal(canSetProfileIntake("GKS-U", "gks_u", "2028", 2027, now), false);
assert.equal(canSetProfileIntake("GKS-U", "gks_u", 2028.5, 2027, now), false);
assert.equal(editionMatches("GKS-U", resolveReadinessIntake("2028","GKS-U","GKS-U",2027)),false);
assert.notEqual(storageKeyFor("GKS-U","embassy","general","2027"), storageKeyFor("GKS-U","embassy","general","2028"));
assert.notEqual(storageKeyFor("GKS-U","embassy","general","2027"), storageKeyFor("GKS-U","embassy","general"));
const app = savedApplicationFromReadiness({program:"GKS-U",track:"embassy",cycle:"2028",universities:[],now});
assert.equal(app.cycle,"2028");
assert.equal(savedApplicationFromReadiness({program:"GKS-U",track:"embassy",cycle:"bad",universities:[],now}).cycle,undefined);
console.log("Intake default, temporary selection, saved cycle and progress isolation checks passed.");
