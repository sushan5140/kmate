import assert from "node:assert/strict";
import { scholarshipAvailability, scholarshipDeadlineLabel, scholarshipSourceFreshness, type AvailabilityInput } from "@/lib/scholarships/availability";
import { classifyScholarshipLifecycle, validScholarshipDate } from "@/lib/scholarships/lifecycle";
const now = new Date("2026-11-26T09:00:00Z");
const base: AvailabilityInput = { deadline: null, deadline_type: null, status:"active", is_active:true,last_verified_at:"2026-11-25T09:00:00Z" };
const get = (patch: Partial<AvailabilityInput>) => scholarshipAvailability({...base,...patch},now);
assert.equal(get({}).kind,"unknown");
assert.equal(get({deadline_type:"automatic"}).kind,"automatic");
assert.equal(get({deadline_type:"admission_schedule"}).kind,"admission");
assert.equal(get({deadline_type:"fixed",deadline:"2026-11-25"}).kind,"archived");
assert.equal(get({deadline_type:"fixed",deadline:"2026-11-25"}).spotlight,false);
assert.equal(get({deadline_type:"fixed",deadline:"2026-11-26"}).kind,"closing");
assert.equal(get({deadline_type:"fixed",deadline:"2026-12-03"}).kind,"closing");
assert.equal(get({deadline_type:"fixed",deadline:"2026-12-04",status:"expiring_soon"}).kind,"fixed");
assert.equal(get({deadline_type:"fixed",deadline:"2026-12-04",last_verified_at:"2026-11-07T09:00:00Z"}).kind,"recheck");
assert.equal(get({deadline_type:"fixed",deadline:"2026-11-25",last_verified_at:null}).kind,"archived");
assert.equal(get({status:"expired",deadline:"2027-01-01",deadline_type:"fixed"}).listed,false);
assert.equal(get({is_active:false,deadline_type:"automatic"}).spotlight,false);
assert.equal(get({last_verified_at:"2026-11-07T09:00:00Z"}).spotlight,false);
assert.equal(get({last_verified_at:"2026-11-07T09:00:00Z"}).listed,true);
assert.equal(get({last_verified_at:null}).kind,"recheck");
assert.equal(get({last_verified_at:"invalid"}).kind,"recheck");
assert.equal(get({last_verified_at:"2026-11-27T09:00:00Z"}).kind,"recheck");
assert.equal(get({deadline_type:"fixed",deadline:"2026-02-30"}).kind,"unknown");
assert.equal(validScholarshipDate("2028-02-29"),true);
assert.equal(validScholarshipDate("2027-02-29"),false);
assert.equal(classifyScholarshipLifecycle({deadline_type:"fixed",deadline:"2026-02-30"},now).status,"active");
assert.equal(scholarshipSourceFreshness("2026-11-12T09:00:00Z",now).state,"fresh");
assert.equal(scholarshipSourceFreshness("2026-11-12T08:59:59Z",now).state,"aging");
assert.equal(scholarshipSourceFreshness("2026-10-27T09:00:00Z",now).state,"aging");
assert.equal(scholarshipSourceFreshness("2026-10-27T08:59:59Z",now).state,"stale");
assert.equal(scholarshipDeadlineLabel({deadline_type:"fixed",deadline:"2026-12-03"}),"December 3, 2026");
assert.ok(scholarshipDeadlineLabel({deadline_type:"automatic",deadline:"2026-11-25"}).includes("consideration"));
assert.equal(scholarshipDeadlineLabel({deadline_type:"fixed",deadline:null}),"Not confirmed in the indexed source");
for (const input of [{},{deadline_type:"automatic"},{deadline_type:"fixed",deadline:"2026-12-04"},{deadline_type:"fixed",deadline:"2026-11-26"},{deadline_type:"admission_schedule"}]) {
 const availability = get(input);
 assert.ok(!/^active$|^open$|^applications open$/i.test(availability.label));
}
console.log("R4 scholarship source freshness, date validity and availability checks passed.");
