import assert from "node:assert/strict";
import { createSavedApplication } from "../../../lib/applications/model";
import { clearStageScope, MAX_STAGE_ENTRIES, parseStageEntries, stageEntryFor, stageScope, stageStatusesFor, stageTargets, upsertStageEntry, validStageCycle, validStageDate, type StageEntry } from "../../../lib/applications/stage-tracker";

const app = createSavedApplication({ program: "GKS-G", track: "embassy", universities: [{ name: "Example University", major: "CS" }, { name: "Other University" }], now: new Date("2026-11-26T00:00:00Z") });
const scope = stageScope(app, "2027");
assert.ok(scope);
assert.equal(stageScope(app, "2026") === scope, false);
assert.equal(stageScope(app, "") , null);
assert.equal(stageScope({ ...app, status: "archived" }, "2027"), null);
assert.equal(stageScope({ ...app, program: "GKS-U" }, "2027") === scope, false);
assert.equal(stageScope({ ...app, track: "university" }, "2027") === scope, false);
assert.equal(stageScope({ ...app, subtype: "research" }, "2027") === scope, false);
assert.equal(stageScope({ ...app, universities: [{ ...app.universities[0], major: "Physics" }, app.universities[1]] }, "2027") === scope, false);
assert.equal(stageScope({ ...app, universities: app.universities.slice().reverse() }, "2027"), scope);
assert.equal(stageScope({ ...app, universities: app.universities.slice(1) }, "2027") === scope, false);
assert.equal(stageScope({ ...app, id: "another-application" }, "2027") === scope, false);
const targets = stageTargets(app);
assert.equal(targets.length, 4);
assert.equal(targets[0].id, "embassy");
assert.equal(targets[1].kind, "university_review");
assert.equal(targets[3].id, "overall");
assert.equal(stageStatusesFor(targets[3]).includes("receipt_confirmed"), false);
assert.equal(stageStatusesFor(targets[0]).includes("receipt_confirmed"), true);
const universityTargets = stageTargets({ ...app, track: "university" });
assert.equal(universityTargets.length, 3);
assert.ok(universityTargets.every(t => t.id !== "embassy"));
assert.equal(universityTargets[0].kind, "first_round");
assert.equal(validStageDate("2026-02-30"), false);
assert.equal(validStageDate("2028-02-29"), true);
assert.equal(validStageCycle("20a7"), false);
const record: StageEntry = { scope, targetId: targets[0].id, status: "submitted", eventDate: "2026-11-25", nextCheck: "" };
assert.deepEqual(parseStageEntries(null), []);
assert.deepEqual(parseStageEntries("{bad json"), []);
assert.deepEqual(parseStageEntries("{}"), []);
assert.deepEqual(parseStageEntries(JSON.stringify([record, record, { ...record, targetId: "bad", status: "invented" }, { ...record, targetId: "bad-date", eventDate: "2026-02-30" }, null])), [record]);
const saved = upsertStageEntry([], record);
assert.ok(saved);
assert.deepEqual(stageEntryFor(saved, scope, targets[0]), record);
assert.equal(stageEntryFor(saved, stageScope(app, "2026")!, targets[0]), undefined);
assert.equal(stageEntryFor(saved, scope, targets[1]), undefined);
assert.equal(stageEntryFor([{ ...record, targetId: "overall" }], scope, targets[3]), undefined);
assert.deepEqual(upsertStageEntry(saved, { ...record, status: "receipt_confirmed" }), [{ ...record, status: "receipt_confirmed" }]);
assert.equal(upsertStageEntry(saved, { ...record, eventDate: "bad" }), null);
const old = { ...record, scope: stageScope(app, "2026")! };
assert.deepEqual(clearStageScope([old, record], scope), [old]);
const full = Array.from({ length: MAX_STAGE_ENTRIES }, (_, i) => ({ ...record, scope: "scope-" + i }));
assert.equal(upsertStageEntry(full, record), null);
assert.equal(upsertStageEntry(full, { ...full[0], status: "selected" })?.length, MAX_STAGE_ENTRIES);
console.log("Application stage tracker regression checks passed.");
